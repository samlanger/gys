#!/usr/bin/env python3
"""Build app/data.js from the taxonomy, researched case cards and preview stubs.

    python3 app/build.py

Researched cards in /cases/*.json win over preview stubs with the same id.
Re-run after adding or editing cases or taxonomy.md.
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "app" / "data.js"

FIELD_KEYS = {
    "Definition": "definition", "Includes": "includes", "Excludes": "excludes",
    "Mechanism": "mechanism", "Second-order risks": "risks",
    "Niche/hub tendency": "niche_hub", "Illustrative": "illustrative",
}


def parse_taxonomy():
    text = (ROOT / "schema" / "taxonomy.md").read_text()
    types, family = [], None
    for block in re.split(r"^(?=## |### )", text, flags=re.M):
        head = block.splitlines()[0] if block.strip() else ""
        fam = re.match(r"## Family ([A-Z]) — (.+)", head)
        if fam:
            family = {"letter": fam.group(1), "name": fam.group(2).strip()}
            continue
        if head.startswith("## "):
            family = None
            continue
        code = re.match(r"### ([a-z_]+)\s*$", head)
        if not code or not family:
            continue
        entry = {"code": code.group(1), "family": family["letter"], "family_name": family["name"]}
        for label, key in FIELD_KEYS.items():
            m = re.search(r"\*\*" + re.escape(label) + r":\*\*\s*(.+)", block)
            if m:
                entry[key] = m.group(1).strip()
        types.append(entry)
    return types


def pop_band(n):
    if n is None:
        return None
    return "tiny" if n < 5000 else "small" if n < 50000 else "medium" if n < 500000 else "large"


def card_to_feature(card):
    """Reduce a full case card to the flat feature record the app matches on."""
    place, sc = card["place"], card["starting_conditions"]
    pops = [o["value"] for o in place.get("population", []) if o.get("value") is not None]
    hours = (sc.get("access", {}).get("travel_time_to_metro_hours") or {}).get("value")
    remoteness = None
    if isinstance(hours, (int, float)):
        remoteness = "metro" if hours <= 1.5 else "regional" if hours <= 4 else "remote"
    nvh = card["niche_vs_hub_assessment"]
    return {
        "id": card["meta"]["case_id"],
        "name": place["name"],
        "country": place["country"],
        "continent": card["meta"].get("continent"),
        "pop_band": pop_band(pops[-1] if pops else None),
        "remoteness": remoteness,
        "declining": any(d["driver"] != "none_not_in_decline" for d in sc.get("decline_drivers", [])),
        "settings": sc["geography"]["settings"],
        "sectors": sc["economy"]["primary_sectors"],
        "assets": card["meta"].get("app_asset_tags", []),
        "triggers": card["trigger"]["types"],
        "interventions": sorted({i["type"] for i in card["interventions"]}),
        "start": str(card["meta"]["era"]["start_year"]),
        "outcome": card["outcome"]["classification"]["label"],
        "archetype": nvh["current_archetype"]["archetype"],
        "effects": sorted({e["domain"] for e in card["second_order_effects"]}),
        "summary": card["trigger"]["description"]["value"],
        "lesson": card["lessons"][0]["lesson"] if card["lessons"] else "",
        "verified": True,
    }


def main():
    preview = json.loads((ROOT / "data" / "preview_cases.json").read_text())
    cases = {c["id"]: {**c, "verified": False} for c in preview["cases"]}
    for path in sorted((ROOT / "cases").glob("*.json")):
        card = json.loads(path.read_text())
        cases[card["meta"]["case_id"]] = card_to_feature(card)
    data = {"types": parse_taxonomy(), "cases": list(cases.values())}
    OUT.write_text("// Generated by app/build.py. Do not edit by hand.\nwindow.ATLAS = "
                   + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
    verified = sum(c["verified"] for c in data["cases"])
    print(f"wrote {OUT.relative_to(ROOT)}: {len(data['types'])} types, "
          f"{len(data['cases'])} cases ({verified} researched, {len(data['cases']) - verified} preview)")


if __name__ == "__main__":
    main()
